import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { format } from 'oxfmt';

// Official resources listed at https://data.gov.tw/dataset/14718.
// New years and changed totals require review before adding them here.
const resources = [
  {
    year: 2026,
    filename: '202506/a52331bd-a189-466b-b0f0-cae3062bbf74.csv',
    name: '115年中華民國政府行政機關辦公日曆表.csv',
    expectedOff: 120,
    expectedEvents: 22,
  },
  {
    year: 2027,
    filename: '202607/f538b1ff-ba60-4c63-9477-10db8e6612d1.csv',
    name: '116年中華民國政府行政機關辦公日曆表_utf8bom.csv',
    expectedOff: 121,
    expectedEvents: 24,
  },
];
const knownNotes = new Set([
  '',
  '開國紀念日',
  '小年夜',
  '農曆除夕',
  '春節',
  '補假',
  '和平紀念日',
  '兒童節',
  '清明節',
  '勞動節',
  '端午節',
  '中秋節',
  '孔子誕辰紀念日/教師節',
  '國慶日',
  '臺灣光復暨金門古寧頭大捷紀念日',
  '行憲紀念日',
]);
const snapshots = [];

for (const resource of resources) {
  const { year } = resource;
  const query = new URLSearchParams({
    filename: `dgpa/files/${resource.filename}`,
    name: resource.name,
    nfix: '',
  });
  const sourceUrl = `https://www.dgpa.gov.tw/FileConversion?${query}`;
  // macOS curl uses the system trust store; do not disable TLS verification.
  const bytes = execFileSync(
    'curl',
    ['--fail', '--silent', '--show-error', '--location', '--max-time', '30', sourceUrl],
    { maxBuffer: 1024 * 1024 },
  );
  const lines = new TextDecoder('utf-8', { fatal: true })
    .decode(bytes)
    .replace(/^\uFEFF/u, '')
    .trimEnd()
    .split(/\r?\n/u);
  if (lines.shift() !== '西元日期,星期,是否放假,備註') {
    throw new Error(`${year}: the official CSV schema changed; review the source.`);
  }
  const days = lines.map((line, index) => {
    // This published format has four unquoted columns. Reject schema changes.
    const columns = line.split(',');
    if (columns.length !== 4 || line.includes('"')) {
      throw new Error(`${year}: unexpected CSV fields at row ${index + 2}.`);
    }
    const [compactDate, weekdayName, off, note] = columns;
    const expected = new Date(Date.UTC(year, 0, index + 1));
    const date = expected.toISOString().slice(0, 10);
    if (
      compactDate !== date.replace(/-/g, '') ||
      expected.getUTCFullYear() !== year ||
      weekdayName !== '日一二三四五六'[expected.getUTCDay()] ||
      !['0', '2'].includes(off) ||
      !knownNotes.has(note) ||
      (note !== '' && off !== '2') ||
      (off === '2' && note === '' && ![0, 6].includes(expected.getUTCDay()))
    ) {
      throw new Error(`${year}: unexpected date, weekday or holiday at row ${index + 2}.`);
    }
    return { date, weekday: expected.getUTCDay(), isDayOff: off === '2', note };
  });
  const expectedLength = (Date.UTC(year + 1, 0, 1) - Date.UTC(year, 0, 1)) / 86400000;
  const offCount = days.filter((day) => day.isDayOff).length;
  const eventCount = days.filter((day) => day.note).length;
  if (
    days.length !== expectedLength ||
    offCount !== resource.expectedOff ||
    eventCount !== resource.expectedEvents
  ) {
    throw new Error(`${year}: published totals changed; review before replacing the snapshot.`);
  }
  snapshots.push({
    year,
    fetchedOn: new Date().toISOString().slice(0, 10),
    sourceUrl,
    sourceSha256: createHash('sha256').update(bytes).digest('hex'),
    days,
  });
  console.log(
    `${year}: ${days.length} days, ${offCount} days off, ${eventCount} named events verified.`,
  );
}

// Write only after every year passes, preserving the old snapshot on fetch/validation errors.
const output = new URL('../src/data/calendar.ts', import.meta.url);
const header = `// Generated by scripts/refresh-calendar.mjs from DGPA's official CSV.\n// See docs/research/calendar-sources.md for scope, verification and update instructions.\n\nexport interface CalendarDay {\n  date: string;\n  weekday: number;\n  isDayOff: boolean;\n  note: string;\n}\n\nexport interface CalendarYear {\n  year: number;\n  fetchedOn: string;\n  sourceUrl: string;\n  sourceSha256: string;\n  days: CalendarDay[];\n}\n\n`;
await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
const formatted = await format(
  fileURLToPath(output),
  `${header}export const calendarSnapshots: CalendarYear[] = ${JSON.stringify(snapshots, null, 2)};\n`,
  { singleQuote: true },
);
if (formatted.errors.length) throw new Error('Generated calendar could not be formatted.');
await writeFile(output, formatted.code);
console.log(`Saved ${fileURLToPath(output)}. Review the diff and run tests before publishing.`);
